"""
Write VULCAN results to a self-describing NetCDF file.

All quantities are stored in the CGS units used internally by VULCAN. Index 0 along the
`layer` and `level` dimensions is the bottom of the atmosphere (highest pressure).
"""

from __future__ import annotations

import logging
import os
import time
from datetime import datetime, timezone

import netCDF4 as nc
import numpy as np

log = logging.getLogger('fwl.' + __name__)

FILL = 9.96921e36  # netCDF default fill value for doubles

END_CASES = {
    0: 'not set',
    1: 'converged to steady state',
    2: 'stopped at runtime limit',
    3: 'stopped at count_max limit',
}


def compute_reaction_rates(k, y, M, re_wM_dict, species, nr):
    """
    Compute the rate of every reaction at every layer.

    The rate of reaction i is R_i = k_i * prod(n_s) over its reactants, where the third
    body 'M' contributes the total number density M. A species appearing n times in the
    reactant list contributes n_s**n. This mirrors the rate expressions generated by
    `make_chem_funs.make_chemdf`, so that the net change from all reactions equals `chemdf`.

    Parameters
    ----------
    k : dict
        Rate coefficients, k[i] has shape (nz,).
    y : np.ndarray
        Number densities, shape (nz, ni) [cm-3].
    M : np.ndarray
        Third-body number density, shape (nz,) [cm-3].
    re_wM_dict : dict
        re_wM_dict[i] = [[reactants], [products]], including 'M'.
    species : list
        Species names, ordered as the columns of y.
    nr : int
        Number of reactions; reactions are numbered 1..nr.

    Returns
    -------
    np.ndarray
        Reaction rates, shape (nz, nr) [cm-3 s-1].
    """
    sp_indx = {sp: i for i, sp in enumerate(species)}
    rates = np.zeros((y.shape[0], nr))
    for i in range(1, nr + 1):
        rate = np.array(k[i], dtype=float, copy=True)
        for sp in re_wM_dict[i][0]:
            rate *= M if sp == 'M' else y[:, sp_indx[sp]]
        rates[:, i - 1] = rate
    return rates


def _reaction_types(var, nr):
    """Classify each reaction as thermal, photolysis, photoionisation or condensation."""
    photo = set(getattr(var, 'pho_rate_index', {}).values())
    ion = set(getattr(var, 'ion_rate_index', {}).values())
    conden = set(getattr(var, 'conden_re_list', []))

    types = []
    for i in range(1, nr + 1):
        fwd = i if i % 2 == 1 else i - 1
        if fwd in photo:
            types.append('photolysis')
        elif fwd in ion:
            types.append('photoionisation')
        elif fwd in conden:
            types.append('condensation')
        else:
            types.append('thermal')
    return types


def _on_levels(arr, nz):
    """Place an array defined on the nz-1 interior interfaces onto all nz+1 levels."""
    out = np.full(nz + 1, FILL)
    out[1:-1] = arr
    return out


def _put(ds, name, dims, data, units, long_name, compress=False, **attrs):
    """Create and fill a double-precision variable."""
    v = ds.createVariable(name, 'f8', dims, zlib=compress, fill_value=FILL)
    v.units = units
    v.long_name = long_name
    for key, val in attrs.items():
        setattr(v, key, val)
    v[:] = data
    return v


def _put_str(ds, name, dims, data, long_name):
    """Create and fill a variable-length string variable."""
    v = ds.createVariable(name, str, dims)
    v.long_name = long_name
    v[:] = np.array(data, dtype=object)
    return v


def _attr(value):
    """Convert a value into something storable as a netCDF attribute."""
    if isinstance(value, (bool, np.bool_)):
        return int(value)
    if isinstance(value, (int, float, str, np.integer, np.floating)):
        return value
    return str(value)


def write_netcdf(fpath, var, atm, para, cfg, species, nr, re_wM_dict):
    """
    Write the final state of a VULCAN run to a NetCDF4 file.

    Parameters
    ----------
    fpath : str
        Path of the file to write. It is overwritten if it exists.
    var, atm, para : store.Variables, store.AtmData, store.Parameters
        Model state containers at the end of the run.
    cfg : Config
        Configuration used for the run.
    species : list
        Species names (chem_funs.spec_list).
    nr : int
        Number of reactions (chem_funs.nr).
    re_wM_dict : dict
        Reactants and products of each reaction, including 'M' (chem_funs.re_wM_dict).
    """
    from vulcan import __version__

    nz = cfg.nz
    ni = len(species)
    atoms = list(cfg.atom_list)

    log.info(f'Writing NetCDF output to {fpath}')
    with nc.Dataset(fpath, 'w', format='NETCDF4') as ds:
        # ---------------- Metadata ----------------
        ds.title = 'VULCAN photochemical kinetics output (CGS units)'
        ds.vulcan_version = __version__
        ds.date_created = str(datetime.now(timezone.utc).isoformat(timespec='seconds'))
        ds.hostname = str(os.uname()[1])
        ds.username = str(os.getlogin())
        ds.network = str(cfg.network)
        ds.atom_list = ','.join(atoms)

        end_case = int(getattr(para, 'end_case', 0))
        ds.end_case = end_case
        ds.termination = END_CASES.get(end_case, 'unknown')
        ds.steps = int(para.count)
        ds.model_time_s = float(var.t)
        ds.dt_s = float(var.dt)
        ds.longdy = float(var.longdy)
        ds.longdydt = float(var.longdydt)
        if getattr(para, 'start_time', None) is not None:
            ds.wall_time_s = time.time() - para.start_time

        for key in (
            'Rp',
            'gs',
            'r_star',
            'orbit_radius',
            'sl_angle',
            'f_diurnal',
            'rocky',
            'use_photo',
            'use_ion',
            'use_condense',
            'use_moldiff',
            'nz',
            'P_b',
            'P_t',
        ):
            if hasattr(cfg, key):
                setattr(ds, key, _attr(getattr(cfg, key)))

        # ---------------- Dimensions ----------------
        ds.createDimension('layer', nz)
        ds.createDimension('level', nz + 1)
        ds.createDimension('species', ni)
        ds.createDimension('reaction', nr)
        ds.createDimension('atom', len(atoms))

        # ---------------- Atmospheric structure ----------------
        _put(ds, 'p', ('layer',), atm.pco, 'dyn cm-2', 'pressure at layer centres')
        _put(ds, 'pl', ('level',), atm.pico, 'dyn cm-2', 'pressure at interfaces')
        _put(ds, 'tmp', ('layer',), atm.Tco, 'K', 'temperature at layer centres')
        _put(ds, 'z', ('layer',), atm.zmco, 'cm', 'altitude at layer centres')
        _put(ds, 'zl', ('level',), atm.zco, 'cm', 'altitude at interfaces')
        _put(
            ds,
            'Kzz',
            ('level',),
            _on_levels(atm.Kzz, nz),
            'cm2 s-1',
            'eddy diffusion coefficient',
        )
        _put(
            ds,
            'vz',
            ('level',),
            _on_levels(atm.vz, nz),
            'cm s-1',
            'vertical advection velocity',
        )
        _put(
            ds, 'mean_molecular_weight', ('layer',), atm.mu, 'g mol-1', 'mean molecular weight'
        )
        _put(ds, 'number_density_total', ('layer',), atm.n_0, 'cm-3', 'total number density')
        _put(
            ds,
            'third_body_density',
            ('layer',),
            atm.M,
            'cm-3',
            'third-body (M) number density used in the rate equations',
        )

        # ---------------- Species ----------------
        _put_str(ds, 'species', ('species',), species, 'species name')
        _put(ds, 'molecular_mass', ('species',), atm.ms, 'g mol-1', 'molar mass of species')
        _put(
            ds,
            'N_gas',
            ('layer', 'species'),
            var.y,
            'cm-3',
            'number density',
            compress=True,
        )
        _put(
            ds,
            'x_gas',
            ('layer', 'species'),
            var.ymix,
            '1',
            'volume mixing ratio',
            compress=True,
        )
        _put(
            ds,
            'N_gas_ini',
            ('layer', 'species'),
            var.y_ini,
            'cm-3',
            'initial number density',
            compress=True,
        )

        # ---------------- Reactions ----------------
        ids = np.arange(1, nr + 1)
        v = ds.createVariable('reaction_id', 'i4', ('reaction',))
        v.long_name = 'reaction index (odd = forward, even = reverse of the preceding one)'
        v[:] = ids

        equations = [
            ' + '.join(re_wM_dict[i][0]) + ' -> ' + ' + '.join(re_wM_dict[i][1]) for i in ids
        ]
        _put_str(ds, 'reaction_equation', ('reaction',), equations, 'reaction equation')
        _put_str(ds, 'reaction_type', ('reaction',), _reaction_types(var, nr), 'reaction type')

        v = ds.createVariable('reaction_is_reverse', 'i1', ('reaction',))
        v.long_name = '1 if this is the reverse of reaction_id - 1, else 0'
        v[:] = (ids % 2 == 0).astype(np.int8)

        v = ds.createVariable('reaction_order', 'i4', ('reaction',))
        v.long_name = 'number of reactants including M; sets the units of rate_coefficient'
        v[:] = [len(re_wM_dict[i][0]) for i in ids]

        k_arr = np.stack([np.asarray(var.k[i], dtype=float) for i in ids], axis=1)
        _put(
            ds,
            'rate_coefficient',
            ('layer', 'reaction'),
            k_arr,
            'cm^(3*(reaction_order-1)) s-1',
            'rate coefficient (s-1, cm3 s-1 or cm6 s-1 for reaction_order 1, 2 or 3)',
            compress=True,
        )
        _put(
            ds,
            'reaction_rate',
            ('layer', 'reaction'),
            compute_reaction_rates(var.k, var.y, atm.M, re_wM_dict, species, nr),
            'cm-3 s-1',
            'reaction rate, k times the product of reactant number densities',
            compress=True,
        )

        # ---------------- Element conservation ----------------
        _put_str(ds, 'atom', ('atom',), atoms, 'element')
        _put(
            ds,
            'atom_initial',
            ('atom',),
            [var.atom_ini[a] for a in atoms],
            'cm-3',
            'initial number density of the element, summed over layers',
        )
        _put(
            ds,
            'atom_sum',
            ('atom',),
            [var.atom_sum.get(a, FILL) for a in atoms],
            'cm-3',
            'final number density of the element, summed over layers',
        )
        _put(
            ds,
            'atom_loss',
            ('atom',),
            [var.atom_loss[a] for a in atoms],
            '1',
            'fractional change (atom_sum - atom_initial) / atom_initial',
        )
        if getattr(var, 'atom_conden', None):
            _put(
                ds,
                'atom_conden',
                ('atom',),
                [var.atom_conden.get(a, FILL) for a in atoms],
                'cm-3',
                'number density of the element in condensates, summed over layers',
            )

        # ---------------- Radiation ----------------
        if cfg.use_photo:
            ds.createDimension('wavelength', len(var.bins))
            _put(ds, 'wavelength', ('wavelength',), var.bins, 'nm', 'wavelength')
            _put(
                ds,
                'ba_actinic',
                ('layer', 'wavelength'),
                var.aflux,
                'photons cm-2 s-1 nm-1',
                'actinic flux at layer centres',
                compress=True,
            )
            _put(
                ds,
                'ba_D_SW',
                ('level', 'wavelength'),
                var.sflux,
                'erg cm-2 s-1 nm-1',
                'direct stellar beam at interfaces, not multiplied by cos(zenith angle)',
                compress=True,
            )
            _put(
                ds,
                'ba_U_LW',
                ('level', 'wavelength'),
                var.dflux_u,
                'erg cm-2 s-1 nm-1',
                'upward diffuse flux at interfaces',
                compress=True,
            )
            _put(
                ds,
                'ba_D_LW',
                ('level', 'wavelength'),
                var.dflux_d,
                'erg cm-2 s-1 nm-1',
                'downward diffuse flux at interfaces',
                compress=True,
            )
            _put(
                ds,
                'optdepth',
                ('level', 'wavelength'),
                var.tau,
                '1',
                'vertical optical depth at interfaces, measured from the top',
                compress=True,
            )
